// 用法：把本文件复制为同目录（src/）下的 secrets.h，填入自己的真实值。
//       src/secrets.h 已在 .gitignore 中，不会被提交。
//
// 若不存在 secrets.h，程序使用空默认值：除以下两项外功能均正常 ——
//       1) “邮件提醒”不可用（SMTP 为空）；
//       2) “按键模拟”因大漠插件未注册而失败（Reg 返回非 1）。
//
// 请勿把填好真实值的 secrets.h 提交到公开仓库。
// ============================================================================
#pragma once

// ---------------------------------------------------------------------------
// 一、QQ 邮箱 SMTP —— “邮件提醒”功能使用
//
// 注意：此处填写的是 QQ 邮箱的 **SMTP 授权码**，不是 QQ 登录密码。
// 获取路径：QQ 邮箱网页版 → 设置 → 账户 → 开启“IMAP/SMTP 服务” → 生成授权码。
// ---------------------------------------------------------------------------
#define FINDIMG_SMTP_USER  L"your_account@qq.com"     // 发件邮箱
#define FINDIMG_SMTP_PASS  L"your_smtp_auth_code"     // SMTP 授权码（16 位）
#define FINDIMG_MAIL_TO    L"recipient@example.com"   // 收件邮箱

// ---------------------------------------------------------------------------
// 二、大漠插件注册码 —— “按键模拟”功能使用
//
// 未注册时 dm.dll 的付费接口受限（Reg 返回非 1），按键模拟会直接失败。
// 购买注册码后填入下方即可。
// ---------------------------------------------------------------------------
#define FINDIMG_DM_CODE    L"your_dm_registration_code"

